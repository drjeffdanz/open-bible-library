#!/usr/bin/env python3
"""License and layout checks for the Open Bible Library. Run in CI on every pull request.

Fails if:
  * a catalog entry is missing a license or evidence link, or has an unknown tier/method
  * anything vendored into library/ is not tier "open" (no NC, ND or excluded material in git)
  * a folder under library/<group>/ is not listed in the catalog
  * a file in library/ is 50 MB or larger (GitHub warns at 50 MB, rejects at 100 MB)
  * any source uses a non-commercial license without being excluded
  * known non-redistributable material shows up (CCEL raw folders, merged Sefaria files, source PDFs)
It also regenerates library/NOTICE.md and fails if the committed copy is out of date.
"""

import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
LIB = ROOT / "library"
TIERS = {"open", "open-nd", "excluded"}  # no "noncommercial": the library feeds paid products
METHODS = {"vendored", "mirror", "fetch", "none"}
MAX_BYTES = 50 * 1024 * 1024
FORBIDDEN_NAMES = {"raw-ccel-lake", "merged.json"}
FORBIDDEN_SUFFIXES = {".pdf"}


def build_notice(sources):
    lines = [
        "# Notices and attribution",
        "",
        "Generated by `tools/validate.py --write-notice` from `catalog/sources.yaml`. Do not edit by hand.",
        "",
        "Everything in `library/` is public domain or openly licensed for any use, including commercial use.",
        "When you reuse a dataset, follow its license and credit it as shown below.",
        "",
        "| Folder | Dataset | License | Credit | Evidence |",
        "| --- | --- | --- | --- | --- |",
    ]
    for s in sources:
        if s["method"] != "vendored":
            continue
        credit = s.get("attribution", "Not required")
        lines.append(f"| `{s['path']}` | [{s['name']}]({s['upstream']}) | {s['license']} | {credit} | {s['evidence']} |")
    return "\n".join(lines) + "\n"


def main():
    errors = []
    data = yaml.safe_load((ROOT / "catalog" / "sources.yaml").read_text(encoding="utf-8"))
    sources = data["sources"]
    ids = set()
    vendored_paths = set()

    for s in sources:
        sid = s.get("id", "?")
        if sid in ids:
            errors.append(f"{sid}: duplicate id")
        ids.add(sid)
        for key in ("name", "upstream", "license", "evidence", "tier", "method"):
            if not s.get(key):
                errors.append(f"{sid}: missing '{key}'")
        if s.get("tier") not in TIERS:
            errors.append(f"{sid}: unknown tier {s.get('tier')}")
        if s.get("method") not in METHODS:
            errors.append(f"{sid}: unknown method {s.get('method')}")
        if s.get("method") == "vendored":
            if s.get("tier") != "open":
                errors.append(f"{sid}: only tier 'open' may be vendored into library/ (is {s.get('tier')})")
            p = s.get("path")
            if not p or not (ROOT / p).is_dir():
                errors.append(f"{sid}: vendored path {p} does not exist")
            else:
                vendored_paths.add((ROOT / p).resolve())
            if not s.get("commit"):
                errors.append(f"{sid}: vendored source must pin the upstream commit")
        if "NC" in str(s.get("license", "")).upper().replace("-", " ").split() and s.get("tier") != "excluded":
            errors.append(f"{sid}: non-commercial license must be excluded (library feeds paid products)")
        if s.get("tier") == "excluded" and s.get("method") != "none":
            errors.append(f"{sid}: excluded sources must use method 'none'")

    for group in sorted(p for p in LIB.iterdir() if p.is_dir()):
        for item in sorted(p for p in group.iterdir() if p.is_dir()):
            if item.resolve() not in vendored_paths:
                errors.append(f"{item.relative_to(ROOT)}: folder is not listed in catalog/sources.yaml")

    for f in LIB.rglob("*"):
        if not f.is_file():
            continue
        rel = f.relative_to(ROOT)
        if f.stat().st_size >= MAX_BYTES:
            errors.append(f"{rel}: {f.stat().st_size // (1024 * 1024)} MB is too large for git; mirror it instead")
        if f.name in FORBIDDEN_NAMES or any(part in FORBIDDEN_NAMES for part in rel.parts):
            errors.append(f"{rel}: forbidden (non-redistributable or license-mixed) material")
        if f.suffix.lower() in FORBIDDEN_SUFFIXES:
            errors.append(f"{rel}: scanned PDFs are not vendored; check the scan's own terms")

    notice = build_notice(sources)
    notice_path = LIB / "NOTICE.md"
    if "--write-notice" in sys.argv:
        notice_path.write_text(notice, encoding="utf-8")
        print(f"wrote {notice_path.relative_to(ROOT)}")
    elif not notice_path.exists() or notice_path.read_text(encoding="utf-8") != notice:
        errors.append("library/NOTICE.md is out of date; run: python tools/validate.py --write-notice")

    if errors:
        print("License and layout check FAILED:")
        for e in errors:
            print(f"  - {e}")
        sys.exit(1)
    print(f"OK: {len(sources)} catalog entries, {len(vendored_paths)} vendored datasets checked.")


if __name__ == "__main__":
    main()
